test('create, validate, edit, save, search and persist a workout', async () => {
  const { app, page, userData } = await launch({ env: { TT_NO_TRAY: '1' } })
  await expect(page.getByText('No workouts yet')).toBeVisible()
  await expect(page.locator('.toolbar-title')).toHaveText('Workouts: 0')
  await page.getByRole('button', { name: 'Create workout' }).click()

  const work = page.locator('#input-work')
  await expect(work).toHaveValue('20')
  // invalid input is rejected and the previous value kept
  for (const bad of ['abc', '0', '-5', '1:75', 'Infinity']) {
    await work.fill(bad)
    await work.press('Enter')
    await expect(page.locator('#err-work')).toBeVisible()
    await expect(work).toHaveValue('20')
  }
  await work.fill('1:30')
  await work.press('Enter')
  await expect(work).toHaveValue('01:30')
  await expect(page.locator('#err-work')).toHaveCount(0)
  await page.getByRole('button', { name: 'Increase Work' }).click()
  await expect(work).toHaveValue('01:31')
  await page.locator('#input-cycles').fill('0')
  await page.locator('#input-cycles').press('Enter')
  await expect(page.locator('#err-cycles')).toContainText('1 to 99')
  await page.locator('#input-cycles').fill('4')
  await page.locator('#input-cycles').press('Tab')
  await page.locator('#input-sets').fill('2')
  await page.locator('#input-sets').press('Tab')
  await page.getByRole('textbox', { name: 'Work description' }).fill('יש להגיע ל 1200 הקלדות')

  // name/colour via the summary
  await page.locator('.summary').click()
  const dialog = page.getByRole('dialog', { name: 'Workout settings' })
  await dialog.getByRole('textbox').fill('Leg day אימון')
  await dialog.getByRole('radio', { name: 'Color #0277bd' }).click()
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(page.locator('.summary')).toContainText('2 x Leg day אימון:')

  // explicit save (Ctrl+S)
  await expect(page.getByRole('button', { name: /Save workout/ })).toBeVisible()
  await page.keyboard.press('Control+s')
  await expect(page.getByText('Workout saved')).toBeVisible()
  await expect(page.getByRole('button', { name: /Save workout/ })).toHaveCount(0)

  // unsaved-changes protection
  await page.getByRole('button', { name: 'Increase Rest', exact: true }).click()
  await page.getByRole('button', { name: 'Workout list' }).click()
  const guard = page.getByRole('dialog', { name: 'Unsaved changes' })
  await guard.getByRole('button', { name: 'Cancel' }).click()
  await expect(page.locator('#input-rest')).toHaveValue('11')
  await page.getByRole('button', { name: 'Workout list' }).click()
  await guard.getByRole('button', { name: 'Discard' }).click()
  await expect(page.locator('.toolbar-title')).toHaveText('Workouts: 1')

  const card = page.getByTestId('workout-card')
  await expect(card).toContainText('Work: 01:31 • יש להגיע ל 1200 הקלדות')
  await expect(card).toContainText('Rest: 10 sec')
  await expect(card).toContainText('Sets: 2')
  await expect(card).toHaveCSS('background-color', 'rgb(2, 119, 189)')

  // search
  await page.getByRole('button', { name: 'Search' }).click()
  await page.getByRole('textbox', { name: 'Search workouts' }).fill('leg')
  await expect(card).toHaveCount(1)
  await page.getByRole('textbox', { name: 'Search workouts' }).fill('הקלדות')
  await expect(card).toHaveCount(1)
  await page.getByRole('textbox', { name: 'Search workouts' }).fill('zzz')
  await expect(page.getByText('No matching workouts')).toBeVisible()
  await app.close()

  // persistence across restarts
  const again = await launch({ userData, env: { TT_NO_TRAY: '1' } })
  await expect(again.page.locator('.summary')).toContainText('Leg day אימון: ')
  await expect(again.page.locator('#input-work')).toHaveValue('01:31')
  await again.app.close()
})

test('card menu: preview, settings, notes, favorite, copy, share/import, shortcut, delete', async () => {
  const userData = tempDir()
  seed(userData, referenceWorkouts())
  const { app, page } = await launch({ userData, env: { TT_NO_TRAY: '1' } })
  await expect(page.locator('.toolbar-title')).toHaveText('Workouts: 4')
  const menuFor = async (n: number): Promise<void> => {
    await page.getByRole('button', { name: /More actions for/ }).nth(n).click()
    await expect(page.getByRole('menu')).toBeVisible()
  }
  const item = (name: string | RegExp) => page.getByRole('menuitem', { name })

  // Preview shows the complete generated sequence ending with Finish
  await menuFor(0)
  await item('Preview').click()
  await expect(page.locator('.preview-summary')).toHaveText('5 x Workout: 35:00 • 40 intervals')
  const rows = page.locator('.interval-row')
  await expect(rows).toHaveCount(41)
  await expect(rows.nth(37)).toHaveText('38. Work: 45')
  await expect(rows.nth(38)).toHaveText('39. Rest: 01:00')
  await expect(rows.nth(39)).toHaveText('40. Work: 45')
  await expect(rows.nth(40)).toHaveText('Finish')
  await page.getByRole('button', { name: 'Back' }).click()

  // Settings (name/colour)
  await menuFor(1)
  await item('Settings').click()
  await page.getByRole('dialog').getByRole('textbox').fill('Typing drills')
  await page.getByRole('dialog').getByRole('button', { name: 'Save' }).click()
  await expect(page.getByText('Typing drills')).toBeVisible()

  // Notes (Hebrew)
  await menuFor(0)
  await item('Notes').click()
  await page.getByRole('textbox', { name: 'Notes' }).fill('הערות לאימון\nsecond line')
  await page.getByRole('dialog').getByRole('button', { name: 'Save' }).click()
  await expect(page.getByText('Notes saved')).toBeVisible()
  await menuFor(0)
  await item('Notes').click()
  await expect(page.getByRole('textbox', { name: 'Notes' })).toHaveValue('הערות לאימון\nsecond line')
  await page.keyboard.press('Escape')

  // Favorite + filter
  const firstName = await page.locator('.card-title').nth(2).innerText()
  await menuFor(2)
  await item('Favorite').click()
  await expect(page.getByText('Added to favorites')).toBeVisible()
  await page.getByRole('button', { name: 'Filter and sort' }).click()
  await page.getByRole('menuitemcheckbox', { name: 'Favorites only' }).click()
  await expect(page.getByTestId('workout-card')).toHaveCount(1)
  await expect(page.locator('.toolbar-title')).toHaveText('Workouts: 1')
  await page.getByRole('button', { name: 'Filter and sort' }).click()
  await page.getByRole('menuitemcheckbox', { name: 'Favorites only' }).click()
  await page.getByRole('button', { name: 'Filter and sort' }).click()
  await page.getByRole('menuitemradio', { name: 'Sort: Name' }).click()
  await expect(page.locator('.card-title').first()).toHaveText('Typing drills')

  // Copy assigns a new id
  await page.getByRole('button', { name: 'Filter and sort' }).click()
  await page.getByRole('menuitemradio', { name: 'Sort: Recently edited' }).click()
  await menuFor(0)
  await item('Copy').click()
  await expect(page.locator('.toolbar-title')).toHaveText('Workouts: 5')
  const ids = await page.evaluate(() => window.api.listWorkouts().then((w) => w.map((x) => x.id)))
  expect(new Set(ids).size).toBe(5)
  expect(firstName).toBeTruthy()

  // Share -> JSON file; Import -> new workout
  const exported = path.join(userData, 'export.timertabata.json')
  await setTestHook(app, 'nextSavePath', exported)
  await page.getByRole('button', { name: 'More actions for Typing drills', exact: true }).click()
  await item('Share').click()
  await expect(page.getByText(/Exported to/)).toBeVisible()
  const json = JSON.parse(fs.readFileSync(exported, 'utf8'))
  expect(json).toMatchObject({ format: 'timertabata-workout', version: 1, workout: { name: 'Typing drills', work: 900, workDescription: 'יש להגיע ל 1200 הקלדות' } })
  await setTestHook(app, 'nextOpenPath', exported)
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('button', { name: 'Import workout…' }).click()
  await expect(page.getByText('Imported “Typing drills”')).toBeVisible()
  await expect(page.locator('.toolbar-title')).toHaveText('Workouts: 6')
  // invalid import is rejected
  const bad = path.join(userData, 'bad.json')
  fs.writeFileSync(bad, JSON.stringify({ ...json, workout: { ...json.workout, cycles: 0 } }))
  await setTestHook(app, 'nextOpenPath', bad)
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('button', { name: 'Import workout…' }).click()
  await expect(page.getByText(/Import failed: Not a valid workout file/)).toBeVisible()
  await page.getByRole('button', { name: 'Back' }).click()
  await expect(page.locator('.toolbar-title')).toHaveText('Workouts: 6')

  // Create shortcut (Linux desktop entry / Windows .lnk)
  await page.getByRole('button', { name: /More actions for Workout/ }).first().click()
  await item('Create shortcut').click()
  await expect(page.getByText(/Shortcut created:/)).toBeVisible()
  const files = fs.readdirSync(path.join(userData, 'shortcuts'))
  expect(files).toHaveLength(1)
  if (process.platform === 'linux') {
    const entry = fs.readFileSync(path.join(userData, 'shortcuts', files[0]), 'utf8')
    expect(entry).toMatch(/^Exec=.* --workout=[A-Za-z0-9-]+$/m)
  }

  // Delete with confirmation (cancel first)
  const before = await page.getByTestId('workout-card').count()
  await page.getByRole('button', { name: /More actions for/ }).first().click()
  await item('Delete').click()
  await page.getByRole('dialog', { name: 'Delete workout?' }).getByRole('button', { name: 'Cancel' }).click()
  await expect(page.getByTestId('workout-card')).toHaveCount(before)
  await page.getByRole('button', { name: /More actions for/ }).first().click()
  await item('Delete').click()
  await page.getByRole('dialog', { name: 'Delete workout?' }).getByRole('button', { name: 'Delete' }).click()
  await expect(page.getByTestId('workout-card')).toHaveCount(before - 1)
  await app.close()
})

test('editor scrolls while bottom actions stay fixed; keyboard focus reaches controls', async () => {
  const userData = tempDir()
  seed(userData, referenceWorkouts(), { lastWorkoutId: 'ref-purple' })
  const { app, page } = await launch({ userData, env: { TT_NO_TRAY: '1' } })
  await setContentSize(app, 'main', 360, 560)
  await page.waitForFunction(() => window.innerHeight === 560)
  const start = page.getByRole('button', { name: 'START' })
  await expect(start).toBeInViewport()
  await expect(page.locator('#input-coolDown')).not.toBeInViewport()
  await page.locator('#input-coolDown').focus()
  await expect(page.locator('#input-coolDown')).toBeInViewport()
  await expect(start).toBeInViewport()
  const sw = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)
  expect(sw).toBeLessThanOrEqual(0)
  // accessible names on icon-only controls
  for (const name of ['Preview', 'History', 'Settings', 'Workout list', 'New workout', 'Increase Prepare', 'Decrease Prepare'])
    await expect(page.getByRole('button', { name, exact: true })).toHaveCount(1)
  await app.close()
})

